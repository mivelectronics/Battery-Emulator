"""Writes miv_page_gz.h from miv_page.html: the page gzipped, as a PROGMEM byte array.

    python gen_page.py

Run after every change to miv_page.html and commit both files: the firmware build does not run it.
mtime 0 in the gzip header keeps the output the same for the same input.
"""
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "miv_page.html")
OUT = os.path.join(HERE, "miv_page_gz.h")

raw = open(SRC, "rb").read()
gz = gzip.compress(raw, compresslevel=9, mtime=0)
lines = [", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
with open(OUT, "w", encoding="ascii", newline="\n") as f:
    f.write("#pragma once\n\n")
    f.write("// AUTO-GENERATED by gen_page.py from miv_page.html - do not edit.\n")
    f.write(f"// {len(raw)} bytes of HTML, {len(gz)} gzipped\n\n")
    f.write("#include <pgmspace.h>\n#include <stdint.h>\n\n")
    f.write("static const uint8_t miv_page_gz[] PROGMEM = {\n  " + ",\n  ".join(lines) + "\n};\n")
print(f"{len(raw)} bytes -> {len(gz)} gzipped -> {OUT}")
