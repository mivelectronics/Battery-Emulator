"""Turns the upstream capture test/can_log_based/can_logs/17_Kia64_UDSpolls.txt into the table of
UDS answers for the bench simulator (s32k/app/emulator/port/sim_kona_uds.inc).
Usage: python gen_sim_uds.py <log> <out>
"""
import re
import sys

log, out = sys.argv[1:3]
responses = {}
pid = None
for line in open(log):
    m = re.search(r"(TX5|rx4) (7e4|7ec) \[8\] ((?:[0-9a-f]{2} ?){8})", line)
    if not m:
        continue
    d = [int(x, 16) for x in m.group(3).split()]
    if m.group(2) == "7e4":
        if d[0] == 0x03 and d[1] == 0x22:
            pid = (d[2] << 8) | d[3]
            responses[pid] = []
    elif pid is not None:
        responses[pid].append(d)

with open(out, "w", newline="\n") as f:
    f.write("/* Generated by s32k/tools/gen_sim_uds.py from 17_Kia64_UDSpolls.txt, do not edit */\n")
    f.write("struct sim_uds_response {\n\tuint16_t pid;\n\tuint8_t n_frames;\n\tuint8_t frames[%d][8];\n};\n\n"
            % max(len(v) for v in responses.values()))
    f.write("static const struct sim_uds_response sim_uds_responses[] = {\n")
    for p, frames in responses.items():
        f.write("\t{0x%04X, %d, {\n" % (p, len(frames)))
        for d in frames:
            f.write("\t\t{%s},\n" % ", ".join("0x%02X" % x for x in d))
        f.write("\t}},\n")
    f.write("};\n")
print({hex(k): len(v) for k, v in responses.items()})
